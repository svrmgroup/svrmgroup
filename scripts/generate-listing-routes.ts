// Regenerates src/seo/listingRoutes.generated.ts and the listing block of public/sitemap.xml
// from the fleet and stay data. Run: bun scripts/generate-listing-routes.ts
import fs from "fs";
import { allListingPaths } from "../src/data/listings";

const routes = allListingPaths().map((r) => ({ ...r, image: /^https:\/\//.test(r.image) ? r.image : r.image.startsWith("/__l5e/") ? `https://svrm.group${r.image}` : undefined }));
const body = `// GENERATED by scripts/generate-listing-routes.ts — do not edit by hand.
// Node-safe copy of every listing detail page for build-time static heads and the sitemap.
export const LISTING_ROUTES: { path: string; title: string; description: string; heading: string; summary: string; image?: string }[] = ${JSON.stringify(routes, null, 1)};
`;
fs.writeFileSync("src/seo/listingRoutes.generated.ts", body);

const sm = "public/sitemap.xml";
let xml = fs.readFileSync(sm, "utf8").replace(/\n  <!-- listings:start -->[\s\S]*<!-- listings:end -->/, "");
const entries = routes.map((r) => `  <url><loc>https://svrm.group${r.path}</loc><changefreq>monthly</changefreq><priority>0.8</priority></url>`).join("\n");
xml = xml.replace("</urlset>", `  <!-- listings:start -->\n${entries}\n  <!-- listings:end -->\n</urlset>`);
fs.writeFileSync(sm, xml);
console.log(`${routes.length} listing routes`);
